"""Build the static GitHub Pages site from the raw Squarespace snapshot in _original/.

Usage: python3 tools/build.py

Each _original/<path>/index.html is rewritten to <path>/index.html with:
  - Squarespace CDN URLs pointed at the local mirror under /assets/<host>/...
  - Adobe Typekit replaced by the self-hosted stand-ins in /assets/fonts/fonts.css
  - Squarespace-only features (search, analytics, RSS, cookie banner) removed
  - Page-specific content changes from CONTENT_EDITS applied

Re-running is safe: generated pages are overwritten, _original/ is never touched.
"""
import os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_original")
HOSTS = ("images.squarespace-cdn.com", "static1.squarespace.com", "assets.squarespace.com",
         "definitions.sqspcdn.com", "file.squarespace-cdn.com")
SITE = "https://www.megbrennan.com"
# Footer text block that reads "POWERED BY SQUARESPACE", removed from every page
FOOTER_CREDIT_BLOCK = "block-bed96c51e290f122bd94"
# Footer links (FAQ, Terms, Privacy, Volunteer, Donate, Contact Us) left over from the Mojave
# template, removed from every page
# Placeholder pages from the Mojave template (lorem ipsum), not built
SKIP_PAGES = {"faq-mojave", "terms-of-service-mojave", "privacy-policy-mojave"}
FOOTER_NAV = re.compile(r'\s*<nav class="Footer-nav"[^>]*>.*?</nav>', re.S)


def rewrite_asset_urls(html):
    for host in HOSTS:
        # Plain, protocol-relative, http and JSON-escaped (https:\/\/host\/) forms
        html = re.sub(r"(?:https?:)?//" + re.escape(host) + "/", f"/assets/{host}/", html)
        html = re.sub(r"(?:https?:)?\\/\\/" + re.escape(host) + r"\\/", f"\\/assets\\/{host}\\/", html)
    return html


def swap_fonts(html):
    html = re.sub(r'<script[^>]*src="//use\.typekit\.net/[^"]*"[^>]*></script>\s*', "", html)
    html = re.sub(r"<script>try\{Typekit\.load[^<]*</script>\s*", "", html)
    html = html.replace("<script>document.documentElement.classList.add('wf-loading')</script>", "")
    html = re.sub(r'<link rel="preconnect" href="https://(use|p)\.typekit\.net"[^>]*>\s*', "", html)
    html = re.sub(r'<link rel="preconnect" href="https://[a-z0-9.-]*squarespace[a-z0-9.-]*\.com"[^>]*>\s*', "", html)
    return html.replace("</head>", '<link rel="stylesheet" href="/assets/fonts/fonts.css">\n</head>', 1)


def strip_squarespace_services(html):
    # RSS feeds were generated by Squarespace and no longer exist
    html = re.sub(r'<link rel="alternate" type="application/rss\+xml"[^>]*>\s*', "", html)
    # Drop the Squarespace runtime (loader, analytics, telemetry, editor hooks); keep structured data.
    # assets/site/site.js reimplements the parts the template needs.
    html = re.sub(r'<script\b(?![^>]*application/ld\+json)[^>]*>.*?</script>\s*', "", html, flags=re.S)
    html = html.replace("</head>", '<link rel="stylesheet" href="/assets/site/site.css">\n</head>', 1)
    return html.replace("</body>", '<script src="/assets/site/site.js" defer></script>\n</body>', 1)


def remove_block(html, block_id):
    """Remove one Squarespace content block (<div class="sqs-block ..." id=...>) and its subtree."""
    m = re.search(r'<div class="sqs-block [^"]*"[^>]*id="' + re.escape(block_id) + '"[^>]*>', html)
    if not m:
        raise ValueError(f"block {block_id} not found")
    depth, pos = 1, m.end()
    for tag in re.finditer(r"<(/?)div\b[^>]*>", html[pos:]):
        depth += -1 if tag.group(1) else 1
        if depth == 0:
            return html[:m.start()] + html[pos + tag.end():]
    raise ValueError(f"block {block_id} is unbalanced")


# Phase 3 content changes, keyed by page directory
CONTENT_EDITS = {
    # The Squarespace form handler goes away with the subscription, so the form (and the divider
    # above it) is dropped; email and Instagram links stay.
    "contact": [
        ("remove", "block-yui_3_17_2_1_1536934884119_4679"),  # horizontal rule
        ("remove", "block-yui_3_17_2_1_1536934884119_3982"),  # contact form
        ("replace", '>Instagram</a>, or use the form below! </p>', '>Instagram</a>! </p>'),
        ("replace", 'directly at <a href="mailto:megbrennanmusic@gmail.com" target="_blank">megbrennanmusic@gmail.com</a>, connect',
                    'directly at <a href="mailto:megbrennanmusic@gmail.com" target="_blank">megbrennanmusic@gmail.com</a> or connect'),
    ],
}


def apply_content_edits(rel_dir, html):
    for edit in CONTENT_EDITS.get(rel_dir, []):
        if edit[0] == "remove":
            html = remove_block(html, edit[1])
        else:
            if edit[1] not in html:
                raise ValueError(f"{rel_dir}: text not found: {edit[1]}")
            html = html.replace(edit[1], edit[2])
    return html


def build_page(rel_dir):
    src = os.path.join(SRC, rel_dir, "index.html")
    html = open(src, encoding="utf-8").read()
    html = rewrite_asset_urls(html)
    html = swap_fonts(html)
    html = strip_squarespace_services(html)
    if 'id="' + FOOTER_CREDIT_BLOCK + '"' in html:
        html = remove_block(html, FOOTER_CREDIT_BLOCK)
    html = FOOTER_NAV.sub("", html)
    html = apply_content_edits(rel_dir, html)
    dest = os.path.join(ROOT, rel_dir, "index.html")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    open(dest, "w", encoding="utf-8").write(html)
    return dest


def redirect_page(target):
    return (f'<!doctype html>\n<meta charset="utf-8">\n<title>Redirecting</title>\n'
            f'<link rel="canonical" href="{SITE}{target}">\n'
            f'<meta http-equiv="refresh" content="0; url={target}">\n'
            f'<a href="{target}">Continue to {target}</a>\n')


def not_found_page():
    """404.html for GitHub Pages, reusing a built page's header and footer."""
    html = open(os.path.join(ROOT, "short", "index.html"), encoding="utf-8").read()
    body = ('<main class="Main Main--page"><section class="Main-content">'
            '<div class="sqs-layout"><div class="sqs-block html-block sqs-block-html"><div class="sqs-block-content">'
            '<h1 style="text-align:center">Page not found</h1>'
            '<p style="text-align:center">Sorry, that page doesn\'t exist. <a href="/">Go to the homepage</a>.</p>'
            '</div></div></div></section></main>')
    html = re.sub(r"<main\b.*?</main>", lambda m: body, html, count=1, flags=re.S)
    html = re.sub(r"<title>.*?</title>", "<title>Page Not Found &mdash; Meg Brennan</title>", html, count=1)
    open(os.path.join(ROOT, "404.html"), "w", encoding="utf-8").write(html)


def main():
    pages = []
    for dp, _, fs in os.walk(SRC):
        if "index.html" in fs:
            pages.append(os.path.relpath(dp, SRC).replace(".", "", 1) if dp == SRC else os.path.relpath(dp, SRC))
    for rel in sorted(p for p in pages if p not in SKIP_PAGES):
        print("page", "/" + rel.strip("/"), "->", os.path.relpath(build_page(rel), ROOT))

    # Squarespace redirects (e.g. /bio-1 -> /short) become meta-refresh pages
    for line in open(os.path.join(SRC, "_redirects.txt")):
        old, new = line.split()
        dest = os.path.join(ROOT, old.strip("/"), "index.html")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        open(dest, "w").write(redirect_page(new))
        print("redirect", old, "->", new)

    # File downloads served by Squarespace at /s/<name>
    shutil.copytree(os.path.join(SRC, "s"), os.path.join(ROOT, "s"), dirs_exist_ok=True)
    # Icon sprites and placeholders Squarespace served from the site's own domain
    shutil.copy(os.path.join(SRC, "assets", "ui-icons.svg"), os.path.join(ROOT, "assets", "ui-icons.svg"))
    shutil.copytree(os.path.join(SRC, "universal"), os.path.join(ROOT, "universal"), dirs_exist_ok=True)
    not_found_page()


if __name__ == "__main__":
    main()
